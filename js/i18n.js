const STORAGE_KEY = "hostera-lang";

const applyLanguage = (lang) => {
  const pack = translations[lang] || translations.en;
  document.documentElement.lang = lang;
  document.title = pack["meta.title"];
  const description = document.querySelector('meta[name="description"]');
  if (description) description.setAttribute("content", pack["meta.description"]);

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const value = pack[node.dataset.i18n];
    if (value != null) node.textContent = value;
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((node) => {
    const value = pack[node.dataset.i18nAlt];
    if (value != null) node.setAttribute("alt", value);
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((node) => {
    const value = pack[node.dataset.i18nAria];
    if (value != null) node.setAttribute("aria-label", value);
  });

  document.querySelectorAll("[data-lang]").forEach((control) => {
    const current = control.dataset.lang === lang;
    if (current) control.setAttribute("aria-current", "page");
    else control.removeAttribute("aria-current");
  });
};

const setLanguage = (lang) => {
  const next = translations[lang] ? lang : "en";
  applyLanguage(next);
  localStorage.setItem(STORAGE_KEY, next);
  const url = new URL(window.location.href);
  url.searchParams.set("lang", next);
  window.history.replaceState({}, "", url);
};

const initial =
  new URLSearchParams(window.location.search).get("lang") ||
  localStorage.getItem(STORAGE_KEY) ||
  "en";

applyLanguage(translations[initial] ? initial : "en");

document.querySelectorAll("[data-lang]").forEach((control) => {
  control.addEventListener("click", (event) => {
    event.preventDefault();
    setLanguage(control.dataset.lang);
  });
});
